// Copies zephyr_scion's tools/imcu/registers.inc (the named MDIN registers for `@out` lines)
// into lib/src/registers_inc.dart, so the compiler resolves names on every platform without
// file access. test/registers_test.dart fails when the copy is stale.
//   dart run tool/gen_registers.dart [path/to/registers.inc]
import 'dart:io';

void main(List<String> args) {
  final src = File(args.isEmpty ? '../../tools/imcu/registers.inc' : args.first).readAsStringSync();
  if (src.contains("'''")) throw StateError("registers.inc contains ''' and cannot be embedded as is");
  File('lib/src/registers_inc.dart').writeAsStringSync('''// GENERATED by tool/gen_registers.dart from zephyr_scion tools/imcu/registers.inc. Do not edit.
const registersInc = r\'\'\'
$src\'\'\';
''');
  stdout.writeln('lib/src/registers_inc.dart: ${src.split('\n').length} lines');
}
